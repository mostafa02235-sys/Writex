#!/usr/bin/env python3
"""Generate every Writex icon from the supplied artwork (assets/icon-source.png).

Run:  python3 scripts/make-icons.py
Writes Android launcher/adaptive icons and splash images into
assets/android-res/ (copied into android/app/src/main/res by scripts/apply-android.mjs),
plus web icons and the in-app logo.
"""
import base64, io, os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'icon-source.png')
RES = os.path.join(ROOT, 'assets', 'android-res')
WEB = os.path.join(ROOT, 'web', 'icons')

art = Image.open(SRC).convert('RGB')
W, H = art.size
# Bounds of the glowing tile (everything brighter than near-black)
px = art.load()
xs, ys = [], []
for y in range(0, H, 2):
    for x in range(0, W, 2):
        if max(px[x, y]) > 40:
            xs.append(x); ys.append(y)
cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
content = max(max(xs) - min(xs), max(ys) - min(ys))

def framed(fill):
    """Square image, black outside the artwork, where the tile spans `fill` of the side."""
    side = int(round(content / fill))
    canvas = Image.new('RGB', (side, side), (0, 0, 0))
    canvas.paste(art, (int(round(side / 2 - cx)), int(round(side / 2 - cy))))
    return canvas

def save(img, path, size):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.resize((size, size), Image.LANCZOS).save(path, optimize=True)

DENS = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
legacy = framed(0.86)          # classic square launcher icon
adaptive = framed(0.60)        # foreground: tile stays inside the 66dp safe zone of 108dp
for d, k in DENS.items():
    save(legacy, f'{RES}/mipmap-{d}/ic_launcher.png', int(48 * k))
    # Round launchers: same art, masked to a circle on black
    r = legacy.resize((int(48 * k),) * 2, Image.LANCZOS)
    roundimg = framed(0.70).resize(r.size, Image.LANCZOS)
    mask = Image.new('L', r.size, 0); ImageDraw.Draw(mask).ellipse((0, 0, r.size[0] - 1, r.size[1] - 1), fill=255)
    out = Image.new('RGBA', r.size, (0, 0, 0, 0)); out.paste(roundimg, (0, 0), mask)
    os.makedirs(f'{RES}/mipmap-{d}', exist_ok=True); out.save(f'{RES}/mipmap-{d}/ic_launcher_round.png', optimize=True)
    save(adaptive, f'{RES}/mipmap-{d}/ic_launcher_foreground.png', int(108 * k))

os.makedirs(f'{RES}/mipmap-anydpi-v26', exist_ok=True)
adaptive_xml = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
'''
for n in ('ic_launcher', 'ic_launcher_round'):
    open(f'{RES}/mipmap-anydpi-v26/{n}.xml', 'w').write(adaptive_xml)
os.makedirs(f'{RES}/values', exist_ok=True)
open(f'{RES}/values/ic_launcher_background.xml', 'w').write(
    '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#000000</color>\n    <color name="splash_background">#000000</color>\n</resources>\n')

# Splash icon. Android 12+ shows a 288dp canvas and keeps only a 192dp circle,
# so the tile takes half the canvas. Older Android versions draw it centred on black
# through drawable/splash.xml.
for d, k in DENS.items():
    save(framed(0.50), f'{RES}/drawable-{d}/splash_icon.png', int(288 * k))
os.makedirs(f'{RES}/drawable', exist_ok=True)
open(f'{RES}/drawable/splash.xml', 'w').write('''<?xml version="1.0" encoding="utf-8"?>
<!-- Launch screen: the Writex icon centred on AMOLED black (never stretched) -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background" />
    <item android:width="160dp" android:height="160dp" android:gravity="center">
        <bitmap android:src="@drawable/splash_icon" android:gravity="fill" />
    </item>
</layer-list>
''')

# Web / store icons
os.makedirs(WEB, exist_ok=True)
for s in (32, 180, 192, 512):
    save(legacy, f'{WEB}/icon-{s}.png', s)
save(framed(0.60), f'{WEB}/maskable-512.png', 512)
save(legacy, os.path.join(ROOT, 'assets', 'play-store-icon-512.png'), 512)

# In-app logo (embedded so the single-file build works too)
buf = io.BytesIO(); framed(0.98).resize((96, 96), Image.LANCZOS).save(buf, 'PNG', optimize=True)
open(os.path.join(ROOT, 'src', 'brand.js'), 'w').write(
    '// Writex logo (generated by scripts/make-icons.py from assets/icon-source.png)\n'
    'export const LOGO = \'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode() + '\';\n')
print('icons written; tile centre', cx, cy, 'size', content)
